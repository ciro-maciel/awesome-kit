// Writes src/icons.js: the Tabler icons (MIT) the README badges carry, each in its own color,
// embedded as base64 so a build never fetches them. Run once when an icon or a color changes:
//   bun src/make-icons.js <path to @tabler/icons/icons/outline>
import { readFileSync, writeFileSync } from 'node:fs'
import { join } from 'node:path'

// name in the badge -> [Tabler icon, color]
export const ICONS = {
    cartas: ['mail', '#FBBF24'],
    items: ['list-check', '#34D399'],
    Cleaner: ['sparkles', '#60A5FA'],
    Screenshots: ['screenshot', '#F472B6'],
    'Speech to Text': ['microphone', '#F87171'],
    'Text to Speech': ['volume', '#34D399'],
    Windows: ['layout-grid', '#A78BFA'],
    Assistant: ['message-chatbot', '#FBBF24'],
    'CCM Stack': ['stack-2', '#22D3EE'],
    'O Novo Básico': ['books', '#FB923C'],
    'Ferramentas grátis': ['tool', '#A3E635'],
    Infrastructure: ['bolt', '#FACC15'],
    Operations: ['chart-bar', '#38BDF8'],
    Customers: ['users', '#F472B6'],
    Marketing: ['speakerphone', '#FB7185'],
    Agents: ['robot', '#C084FC'],
}

const dir = process.argv[2]
if (!dir) throw new Error('usage: bun src/make-icons.js <path to @tabler/icons/icons/outline>')
const lines = [
    '// Generated by src/make-icons.js: Tabler icons (MIT, tabler.io), one color each, as data URIs',
    '// for shields.io logos. Edit the table in make-icons.js and run it again; never edit this file.',
    'export const ICONS = {',
]
for (const [name, [icon, color]] of Object.entries(ICONS)) {
    const svg = readFileSync(join(dir, `${icon}.svg`), 'utf8')
        .replace(/<!--[\s\S]*?-->/g, '')
        .replace(/\s*class="[^"]*"/, '')
        .replace(/stroke="currentColor"/g, `stroke="${color}"`)
        .replace(/\s+/g, ' ')
        .trim()
    lines.push(`    ${JSON.stringify(name)}: 'data:image/svg+xml;base64,${Buffer.from(svg).toString('base64')}',`)
}
lines.push('}', '')
writeFileSync(new URL('./icons.js', import.meta.url), lines.join('\n'))
console.log(`ok src/icons.js: ${Object.keys(ICONS).length} icons`)
